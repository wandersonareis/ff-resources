// Command gen_key_tables regenera internal/families/white/codecs/ztr/encoding/
// key_tables.go no modelo Tag (classe + par de bytes + nome de display), a
// partir da composição ATUAL dos KeySets — a mesma que o build.go monta.
//
// Uso: go run ./scripts/gen_key_tables
//
// Formato no texto gerado:
//
//	{COLOR:White}         nome resolve o byte (paleta compartilhada)
//	{ICON:F0:40:Clock}    hex autoritativo + nome (só ICON/BTN têm nome)
//	{BTN:F1:40:A}
//	{VAR:F4:40}           ex-{Entity 1}: hex puro, sem nome
//	{CTR:F7:40} {KEY:F6:40} {PAGE:40:70} {NL:40:72} {TAB:85:60} {RAW:81:40}
//
// O gerador também VALIDA que nenhum par de bytes aparece em duas categorias
// do mesmo (jogo, codepage): é a condição que permite uma ordem de consulta
// única no decode e no encode.
package main

import (
	"fmt"
	"os"
	"regexp"
	"strings"

	"ffresources/internal/families/white/codecs/ztr/encoding"
)

const target = "internal/families/white/codecs/ztr/encoding/key_tables.go"

// category é uma categoria de par na ordem de consulta. perGame=true gera um
// mapa por jogo (xiiiColor/xiii2Color/xiii3Color); false gera um mapa único
// (cmnSpecialByCP/cmnRaw/cmnRaw2).
type category struct {
	suffix  string
	perGame bool
	perCP   bool
	field   func(*encoding.KeySet) []encoding.KVPair
}

func categories() []category {
	return []category{
		{"Color", true, true, func(k *encoding.KeySet) []encoding.KVPair { return k.Color }},
		{"Icon", true, true, func(k *encoding.KeySet) []encoding.KVPair { return k.Icon }},
		{"Btn", true, true, func(k *encoding.KeySet) []encoding.KVPair { return k.Btn }},
		// Special varia por CODEPAGE (Entity/Counter/Key), não por jogo.
		{"SpecialByCP", false, true, func(k *encoding.KeySet) []encoding.KVPair { return k.Special }},
		// Raw/Raw2 são comuns a jogos e codepages.
		{"Raw", false, false, func(k *encoding.KeySet) []encoding.KVPair {
			return append(append([]encoding.KVPair{}, k.ExChara...), k.Unk...)
		}},
		{"Raw2", false, false, func(k *encoding.KeySet) []encoding.KVPair { return k.Unk2 }},
	}
}

// varName é o nome da variável gerada: cmnX para as comuns, xiiiX/xiii2X/
// xiii3X para as que variam por jogo.
func varName(cat category, g encoding.GameCode) string {
	if !cat.perGame {
		return "cmn" + cat.suffix
	}
	switch g {
	case encoding.FF131:
		return "xiii" + cat.suffix
	case encoding.FF132:
		return "xiii2" + cat.suffix
	case encoding.FF133:
		return "xiii3" + cat.suffix
	}
	return "xiii?" + cat.suffix
}

var games = []encoding.GameCode{encoding.FF131, encoding.FF132, encoding.FF133}

var cps = []encoding.Codepage{encoding.LatinJapanese, encoding.Chinese, encoding.Korean}

func main() {
	encoding.ClearKeySets()
	for _, g := range games {
		for _, cp := range cps {
			if err := encoding.PrepareKeySet(g, cp); err != nil {
				fatal(err)
			}
		}
	}

	// A validação roda ANTES de escrever: nenhum par em duas categorias.
	if err := validate(); err != nil {
		fatal(err)
	}

	var out strings.Builder
	out.WriteString(header)

	// Singles e chara são copiados do arquivo atual (mudam só os nomes dos
	// singles).
	copyVerbatim(&out, "var cmnSingle = []KVByte{", singleRenames)
	copyVerbatim(&out, "var cmnChara = []CharaEntry{", nil)

	for _, cat := range categories() {
		if cat.perGame {
			for _, g := range games {
				emitMap(&out, varName(cat, g), g, cat)
			}
			continue
		}
		emitMap(&out, varName(cat, encoding.FF131), encoding.FF131, cat)
	}

	out.WriteString("var charaLeadByCP = map[Codepage]byte{\n")
	for _, cp := range cps {
		ks, err := encoding.KeySetFor(encoding.FF131, cp)
		if err != nil {
			fatal(err)
		}
		fmt.Fprintf(&out, "\t%s: 0x%02X,\n", cpName(cp), ks.CharaLead())
	}
	out.WriteString("}\n")

	if err := os.WriteFile(target, []byte(out.String()), 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("key_tables.go regenerado")
}

const header = `// Code generated by scripts/gen_key_tables.go; DO NOT EDIT.
//
// Modelo Tag: a identidade é (classe, par de bytes); o nome é display — o
// MESMO nome existe em bytes diferentes entre jogos (Icon Shield é F2:63 no
// ff132 e F2:5C no ff133), então nome não pode chavear nada.
//
// Formato no texto (o que o tradutor vê):
//
//	{COLOR:White}                 nome resolve o byte (paleta compartilhada)
//	{ICON:F0:40:Clock}            hex AUTORITATIVO + nome de display
//	{BTN:F1:40:A}                 idem (só ICON/BTN têm nome)
//	{VAR:F4:40}                   ex-{Entity 1} do ZTRtool
//	{CTR:F7:40}                   ex-{Counter Type 1}
//	{KEY:F6:40}                   ex-{Key Entity}
//	{PAGE:40:70}                  ex-{TEXT_NEW_PAGE}
//	{NL:40:72}                    ex-{TEXT_NEW_LINE}
//	{TAB:85:60}                   ex-{TEXT_TAB}
//	{RAW:81:40}                   ex-{Unk81 40}/{ExChara85 80}: bytes crus
//	{B:FF}                        0xFF isolado (ex-{FF})
//	{END} {ESC} {TEXT_ITALIC} {TEXT_NORMAL} {LINE} {ART} {ART2}
//	                              controles de byte único (cmnSingle)
//
// Ordem de consulta (decode e encode, unificada): color, icon, btn, chara,
// special, raw, raw2. A unificação só é segura porque nenhum par de bytes
// aparece em duas categorias — o gerador valida isso.

package encoding

`

// emitMap escreve um mapa Codepage -> []Tag (perCP) ou uma lista simples.
// Para as categorias comuns (perGame=false) o jogo é ignorado — o conteúdo é
// o mesmo nos três.
func emitMap(out *strings.Builder, name string, g encoding.GameCode, cat category) {
	if !cat.perCP {
		ks, err := encoding.KeySetFor(g, encoding.LatinJapanese)
		if err != nil {
			fatal(err)
		}
		out.WriteString("var " + name + " = []Tag{\n")
		for _, e := range cat.field(ks) {
			emitTag(out, e)
		}
		out.WriteString("}\n\n")
		return
	}

	out.WriteString("var " + name + " = map[Codepage][]Tag{\n")
	for _, cp := range cps {
		ks, err := encoding.KeySetFor(g, cp)
		if err != nil {
			fatal(err)
		}
		fmt.Fprintf(out, "\t%s: {\n", cpName(cp))
		for _, e := range cat.field(ks) {
			emitTag(out, e)
		}
		out.WriteString("\t},\n")
	}
	out.WriteString("}\n\n")
}

func emitTag(out *strings.Builder, e encoding.KVPair) {
	class, tagName := classify(e.Value)
	if class == "" {
		fatal(fmt.Errorf("tag sem regra de renomeação: %s", e.Value))
	}
	if class == "COLOR" || class == "ICON" || class == "BTN" {
		fmt.Fprintf(out, "\t\t{Class: Class%s, B1: 0x%02X, B2: 0x%02X, Name: %q},\n",
			constName(class), e.B1, e.B2, tagName)
		return
	}
	fmt.Fprintf(out, "\t\t{Class: Class%s, B1: 0x%02X, B2: 0x%02X},\n",
		constName(class), e.B1, e.B2)
}

// constName converte a classe do texto no nome da constante Go
// ("COLOR" -> "Color", "NL" -> "NL").
func constName(class string) string {
	switch class {
	case "COLOR":
		return "Color"
	case "ICON":
		return "Icon"
	case "BTN":
		return "Btn"
	case "VAR":
		return "Var"
	case "CTR":
		return "Ctr"
	case "KEY":
		return "Key"
	case "PAGE":
		return "Page"
	case "TAB":
		return "Tab"
	case "RAW":
		return "Raw"
	}
	return class
}

// copyVerbatim copia um bloco do arquivo atual (singles/chara não mudam de
// forma). renames (quando não é nil) troca os textos das tags.
func copyVerbatim(out *strings.Builder, start string, renames map[string]string) {
	raw, err := os.ReadFile(target)
	if err != nil {
		fatal(err)
	}
	text := strings.ReplaceAll(string(raw), "\r\n", "\n")
	i := strings.Index(text, start)
	if i < 0 {
		fatal(fmt.Errorf("bloco %q não encontrado", start))
	}
	end := strings.Index(text[i:], "\n}\n")
	if end < 0 {
		fatal(fmt.Errorf("fim do bloco %q não encontrado", start))
	}
	block := text[i : i+end+3]
	for old, new := range renames {
		block = strings.ReplaceAll(block, `"`+old+`"`, `"`+new+`"`)
	}
	comment := "// cmnSingle: controles de byte único (0x00..0x05)."
	if strings.HasPrefix(start, "var cmnChara") {
		comment = "// cmnChara: pares de 2 bytes renderizados como runas (não são tags)."
	}
	out.WriteString(comment + "\n")
	out.WriteString(block)
	out.WriteString("\n")
}

// singleRenames: controles de byte único na forma nova.
var singleRenames = map[string]string{
	"{End}":          "{END}",
	"{Escape}":       "{ESC}",
	"{StraightLine}": "{LINE}",
	"{Article}":      "{ART}",
	"{ArticleMany}":  "{ART2}",
}

func cpName(cp encoding.Codepage) string {
	switch cp {
	case encoding.LatinJapanese:
		return "LatinJapanese"
	case encoding.Chinese:
		return "Chinese"
	case encoding.Korean:
		return "Korean"
	}
	return "?"
}

func validate() error {
	for _, g := range games {
		for _, cp := range cps {
			ks, err := encoding.KeySetFor(g, cp)
			if err != nil {
				return err
			}
			seen := map[int]string{}
			check := func(list []encoding.KVPair, label string) error {
				for _, e := range list {
					key := int(e.B1)<<8 | int(e.B2)
					if prev, ok := seen[key]; ok {
						return fmt.Errorf("%s/%s: par %02X %02X em %s e %s",
							g, cpName(cp), e.B1, e.B2, prev, e.Value)
					}
					seen[key] = label + ":" + e.Value
				}
				return nil
			}
			for _, cat := range categories() {
				list := cat.field(ks)
				if len(list) == 0 {
					continue
				}
				if err := check(list, cat.suffix); err != nil {
					return err
				}
			}
		}
	}
	return nil
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen_key_tables:", err)
	os.Exit(1)
}

// ---- regras de renomeação: tag do ZTRtool -> (classe, nome) --------------

var (
	reColor   = regexp.MustCompile(`^\{Color (.+)\}$`)
	reIcon    = regexp.MustCompile(`^\{Icon (.+)\}$`)
	reBtn     = regexp.MustCompile(`^\{Btn (.+)\}$`)
	reEntity  = regexp.MustCompile(`^\{Entity ([1-4])\}$`)
	reCounter = regexp.MustCompile(`^\{Counter Type ([1-3])\}$`)
)

// classify converte a tag antiga em (classe, nome de display). Só COLOR/
// ICON/BTN têm nome; VAR/CTR/KEY e os pares estruturais são hex puro.
func classify(tag string) (class, name string) {
	switch tag {
	case "{TEXT_NEW_PAGE}":
		return "PAGE", ""
	case "{TEXT_NEW_LINE}":
		return "NL", ""
	case "{TEXT_TAB}":
		return "TAB", ""
	case "{Key Entity}":
		return "KEY", ""
	}
	if m := reColor.FindStringSubmatch(tag); m != nil {
		return "COLOR", colorName(m[1])
	}
	if m := reIcon.FindStringSubmatch(tag); m != nil {
		return "ICON", m[1]
	}
	if m := reBtn.FindStringSubmatch(tag); m != nil {
		return "BTN", m[1]
	}
	if m := reEntity.FindStringSubmatch(tag); m != nil {
		return "VAR", ""
	}
	if m := reCounter.FindStringSubmatch(tag); m != nil {
		return "CTR", ""
	}
	// Unk/Unk2/ExChara: bytes crus, sem nome.
	if strings.HasPrefix(tag, "{Unk") || strings.HasPrefix(tag, "{ExChara") {
		return "RAW", ""
	}
	return "", ""
}

// colorName dá nome às cores que o ZTRtool deixou como ExNN.
func colorName(name string) string {
	if strings.HasPrefix(name, "Ex") {
		return "EXTRA" + name[2:]
	}
	return name
}
