// Command emit_key_tables regenera key_tables.go na forma COMPARTILHADA
// (SpanSet: nomes comuns + spans de bytes por codepage), lendo a composição
// atual dos KeySets.
//
// Uso: go run ./scripts/emit_key_tables
//
// É uma migração one-shot: depois de rodar, o arquivo é gerado e a checagem
// de invariantes fica com scripts/keytables_check. Os testes de round-trip
// (testdata + apps/ff13) provam que os BYTES não mudaram.
package main

import (
	"fmt"
	"os"
	"strings"

	"ffresources/internal/families/white/codecs/ztr/encoding"
)

const target = "internal/families/white/codecs/ztr/encoding/key_tables.go"

var games = []encoding.GameCode{encoding.FF131, encoding.FF132, encoding.FF133}
var cps = []encoding.Codepage{encoding.LatinJapanese, encoding.Chinese, encoding.Korean}

// shared é uma categoria que vira SpanSet.
type shared struct {
	suffix string
	class  encoding.TagClass
	field  func(*encoding.KeySet) []encoding.Tag
}

func sharedCategories() []shared {
	return []shared{
		{"Colors", encoding.ClassColor, func(k *encoding.KeySet) []encoding.Tag { return k.Color }},
		{"Icons", encoding.ClassIcon, func(k *encoding.KeySet) []encoding.Tag { return k.Icon }},
		{"Btns", encoding.ClassBtn, func(k *encoding.KeySet) []encoding.Tag { return k.Btn }},
	}
}

func main() {
	encoding.ClearKeySets()
	for _, g := range games {
		for _, cp := range cps {
			if err := encoding.PrepareKeySet(g, cp); err != nil {
				fatal(err)
			}
		}
	}

	var out strings.Builder
	out.WriteString(header)
	copyVerbatim(&out, "var cmnSingle = []KVByte{")
	copyVerbatim(&out, "var cmnChara = []CharaEntry{")
	emitTags(&out, "cmnSpecialByCP", true, func(k *encoding.KeySet) []encoding.Tag { return k.Special })
	emitTags(&out, "cmnRaw", false, func(k *encoding.KeySet) []encoding.Tag { return k.Raw })
	emitTags(&out, "cmnRaw2", false, func(k *encoding.KeySet) []encoding.Tag { return k.Raw2 })
	for _, sc := range sharedCategories() {
		for _, g := range games {
			emitSpanSet(&out, varName(sc.suffix, g), sc.class, sc.field, g)
		}
	}
	out.WriteString("var charaLeadByCP = map[Codepage]byte{\n")
	for _, cp := range cps {
		ks, err := encoding.KeySetFor(encoding.FF131, cp)
		if err != nil {
			fatal(err)
		}
		fmt.Fprintf(&out, "\t%s: 0x%02X,\n", cpName(cp), ks.CharaLead())
	}
	out.WriteString("}\n")

	if err := os.WriteFile(target, []byte(out.String()), 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("key_tables.go regenerado (forma compartilhada)")
}

const header = `// Code generated by scripts/emit_key_tables.go; DO NOT EDIT.
//
// Modelo Tag: a identidade é (classe, par de bytes); o nome é display — o
// MESMO nome existe em bytes diferentes entre jogos (Icon Shield é F2:63 no
// ff132 e F2:5C no ff133), então nome não pode chavear nada.
//
// Formato no texto (o que o tradutor vê):
//
//	{COLOR:White}                 nome resolve o byte (paleta compartilhada)
//	{ICON:F0:40:Clock}            hex AUTORITATIVO + nome de display
//	{BTN:F1:40:A}                 idem (só ICON/BTN têm nome)
//	{VAR:F4:40}                   ex-{Entity 1} do ZTRtool
//	{CTR:F7:40}                   ex-{Counter Type 1}
//	{KEY:F6:40}                   ex-{Key Entity}
//	{PAGE:40:70}                  ex-{TEXT_NEW_PAGE}
//	{NL:40:72}                    ex-{TEXT_NEW_LINE}
//	{TAB:85:60}                   ex-{TEXT_TAB}
//	{RAW:81:40}                   ex-{Unk81 40}/{ExChara85 80}: bytes crus
//	{B:FF}                        0xFF isolado (ex-{FF})
//	{END} {ESC} {TEXT_ITALIC} {TEXT_NORMAL} {LINE} {ART} {ART2}
//	                              controles de byte único (cmnSingle)
//
// Ordem de consulta (decode e encode, unificada): color, icon, btn, chara,
// special, raw, raw2. A unificação só é segura porque nenhum par de bytes
// aparece em duas categorias — scripts/keytables_check valida isso.

package encoding

`

// emitTags escreve uma tabela explícita de Tag (special/raw/raw2 — poucas
// entradas e sem nome, então a forma compartilhada não ganharia nada).
func emitTags(out *strings.Builder, name string, perCP bool, pick func(*encoding.KeySet) []encoding.Tag) {
	if !perCP {
		ks, err := encoding.KeySetFor(encoding.FF131, encoding.LatinJapanese)
		if err != nil {
			fatal(err)
		}
		out.WriteString("var " + name + " = []Tag{\n")
		for _, t := range pick(ks) {
			emitTag(out, t)
		}
		out.WriteString("}\n\n")
		return
	}
	out.WriteString("var " + name + " = map[Codepage][]Tag{\n")
	for _, cp := range cps {
		ks, err := encoding.KeySetFor(encoding.FF131, cp)
		if err != nil {
			fatal(err)
		}
		fmt.Fprintf(out, "\t%s: {\n", cpName(cp))
		for _, t := range pick(ks) {
			emitTag(out, t)
		}
		out.WriteString("\t},\n")
	}
	out.WriteString("}\n\n")
}

func emitTag(out *strings.Builder, t encoding.Tag) {
	if t.Name != "" {
		fmt.Fprintf(out, "\t\t{Class: Class%s, B1: 0x%02X, B2: 0x%02X, Name: %q},\n",
			constName(string(t.Class)), t.B1, t.B2, t.Name)
		return
	}
	fmt.Fprintf(out, "\t\t{Class: Class%s, B1: 0x%02X, B2: 0x%02X},\n",
		constName(string(t.Class)), t.B1, t.B2)
}

// emitSpanSet escreve a forma compartilhada: Names (comum) + Spans por
// codepage. Os nomes vêm da lista do LJ (a ordem canônica).
func emitSpanSet(out *strings.Builder, name string, class encoding.TagClass,
	pick func(*encoding.KeySet) []encoding.Tag, g encoding.GameCode) {

	ksLJ, err := encoding.KeySetFor(g, encoding.LatinJapanese)
	if err != nil {
		fatal(err)
	}
	names := pick(ksLJ)

	out.WriteString("var " + name + " = SpanSet{\n\tNames: []string{\n")
	for _, n := range names {
		fmt.Fprintf(out, "\t\t%q,\n", n.Name)
	}
	out.WriteString("\t},\n\tSpans: map[Codepage][]Span{\n")
	for _, cp := range cps {
		ks, err := encoding.KeySetFor(g, cp)
		if err != nil {
			fatal(err)
		}
		list := pick(ks)
		if len(list) != len(names) {
			fatal(fmt.Errorf("%s/%s: %d entradas, mas LJ tem %d", name, cpName(cp), len(list), len(names)))
		}
		fmt.Fprintf(out, "\t\t%s: {\n", cpName(cp))
		for i := 0; i < len(list); {
			// Um span dura enquanto o lead é o mesmo e o trail é consecutivo.
			j := i + 1
			for j < len(list) && list[j].B1 == list[i].B1 && list[j].B2 == list[j-1].B2+1 {
				j++
			}
			fmt.Fprintf(out, "\t\t\t{Lead: 0x%02X, Trail: 0x%02X, Count: %d, At: %d},\n",
				list[i].B1, list[i].B2, j-i, i)
			i = j
		}
		out.WriteString("\t\t},\n")
	}
	out.WriteString("\t},\n}\n\n")
}

func copyVerbatim(out *strings.Builder, start string) {
	raw, err := os.ReadFile(target)
	if err != nil {
		fatal(err)
	}
	text := strings.ReplaceAll(string(raw), "\r\n", "\n")
	i := strings.Index(text, start)
	if i < 0 {
		fatal(fmt.Errorf("bloco %q não encontrado", start))
	}
	end := strings.Index(text[i:], "\n}\n")
	if end < 0 {
		fatal(fmt.Errorf("fim do bloco %q não encontrado", start))
	}
	block := text[i : i+end+3]
	for old, new := range map[string]string{
		"{End}": "{END}", "{Escape}": "{ESC}", "{StraightLine}": "{LINE}",
		"{Article}": "{ART}", "{ArticleMany}": "{ART2}",
	} {
		block = strings.ReplaceAll(block, `"`+old+`"`, `"`+new+`"`)
	}
	comment := "// cmnSingle: controles de byte único (0x00..0x05)."
	if strings.HasPrefix(start, "var cmnChara") {
		comment = "// cmnChara: pares de 2 bytes renderizados como runas (não são tags)."
	}
	out.WriteString(comment + "\n")
	out.WriteString(block)
	out.WriteString("\n")
}

func varName(suffix string, g encoding.GameCode) string {
	switch g {
	case encoding.FF131:
		return "xiii" + suffix
	case encoding.FF132:
		return "xiii2" + suffix
	case encoding.FF133:
		return "xiii3" + suffix
	}
	return "xiii?" + suffix
}

func constName(class string) string {
	switch class {
	case "COLOR":
		return "Color"
	case "ICON":
		return "Icon"
	case "BTN":
		return "Btn"
	case "VAR":
		return "Var"
	case "CTR":
		return "Ctr"
	case "KEY":
		return "Key"
	case "PAGE":
		return "Page"
	case "NL":
		return "NL"
	case "TAB":
		return "Tab"
	case "RAW":
		return "Raw"
	}
	return class
}

func cpName(cp encoding.Codepage) string {
	switch cp {
	case encoding.LatinJapanese:
		return "LatinJapanese"
	case encoding.Chinese:
		return "Chinese"
	case encoding.Korean:
		return "Korean"
	}
	return "?"
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "emit_key_tables:", err)
	os.Exit(1)
}
